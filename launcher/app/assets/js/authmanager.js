/**
 * Validate the selected account with Mojang's authserver. If the account is not valid,
 * we will attempt to refresh the access token and update that value. If that fails, a
 * new login will be required.
 * 
 * @returns {Promise.<boolean>} Promise which resolves to true if the access token is valid,
 * otherwise false.
 */
async function validateSelectedMojangAccount(){
    const current = ConfigManager.getSelectedAccount()
    const response = await MojangRestAPI.validate(current.accessToken, ConfigManager.getClientToken())

    if(response.responseStatus === RestResponseStatus.SUCCESS) {
        const isValid = response.data
        if(!isValid){
            const refreshResponse = await MojangRestAPI.refresh(current.accessToken, ConfigManager.getClientToken())
            if(refreshResponse.responseStatus === RestResponseStatus.SUCCESS) {
                const session = refreshResponse.data
                ConfigManager.updateMojangAuthAccount(current.uuid, session.accessToken)
                ConfigManager.save()
            } else {
                log.error('Error while validating selected profile:', refreshResponse.error)
                log.info('Account access token is invalid.')
                return false
            }
            log.info('Account access token validated.')
            return true
        } else {
            log.info('Account access token validated.')
            return true
        }
    }
    
}

/**
 * Validate the selected account with Microsoft's authserver. If the account is not valid,
 * we will attempt to refresh the access token and update that value. If that fails, a
 * new login will be required.
 * 
 * @returns {Promise.<boolean>} Promise which resolves to true if the access token is valid,
 * otherwise false.
 */
async function validateSelectedMicrosoftAccount(){
    const current = ConfigManager.getSelectedAccount()
    const now = new Date().getTime()
    const mcExpiresAt = current.expiresAt
    const mcExpired = now >= mcExpiresAt

    if(!mcExpired) {
        return true
    }

    // MC token expired. Check MS token.

    const msExpiresAt = current.microsoft.expires_at
    const msExpired = now >= msExpiresAt

    if(msExpired) {
        // MS expired, do full refresh.
        try {
            const res = await fullMicrosoftAuthFlow(current.microsoft.refresh_token, AUTH_MODE.MS_REFRESH)

            ConfigManager.updateMicrosoftAuthAccount(
                current.uuid,
                res.mcToken.access_token,
                res.accessToken.access_token,
                res.accessToken.refresh_token,
                calculateExpiryDate(now, res.accessToken.expires_in),
                calculateExpiryDate(now, res.mcToken.expires_in)
            )
            ConfigManager.save()
            return true
        } catch(_err) {
            return false
        }
    } else {
        // Only MC expired, use existing MS token.
        try {
            const res = await fullMicrosoftAuthFlow(current.microsoft.access_token, AUTH_MODE.MC_REFRESH)

            ConfigManager.updateMicrosoftAuthAccount(
                current.uuid,
                res.mcToken.access_token,
                current.microsoft.access_token,
                current.microsoft.refresh_token,
                current.microsoft.expires_at,
                calculateExpiryDate(now, res.mcToken.expires_in)
            )
            ConfigManager.save()
            return true
        }
        catch(_err) {
            return false
        }
    }
}

function generateOfflineUUID(username) {
    const hash = crypto.createHash('md5').update('OfflinePlayer:' + username, 'utf8').digest()
    hash[6] = (hash[6] & 0x0f) | 0x30
    hash[8] = (hash[8] & 0x3f) | 0x80
    const hex = hash.toString('hex')
    return [
        hex.substring(0, 8),
        hex.substring(8, 12),
        hex.substring(12, 16),
        hex.substring(16, 20),
        hex.substring(20, 32)
    ].join('-')
}

exports.generateOfflineUUID = generateOfflineUUID

/**
 * Add an offline / nickname account.
 * 
 * @param {string} username The player's desired nickname.
 * @returns {Promise.<Object>} The created account object.
 */
exports.addOfflineAccount = async function(username) {
    if(!username || !username.trim()){
        return Promise.reject(new Error('Никнейм не может быть пустым'))
    }
    const cleanUser = username.trim()
    const uuid = generateOfflineUUID(cleanUser)
    const ret = ConfigManager.addOfflineAuthAccount(uuid, cleanUser)
    ConfigManager.save()
    return ret
}

/**
 * Add or authenticate a password-protected community account.
 * 
 * @param {string} username The player's username.
 * @param {string} password The player's password.
 * @returns {Promise.<Object>} The account object.
 */
exports.addCommunityAccount = async function(username, password) {
    if(!username || !username.trim()){
        return Promise.reject(new Error('Никнейм не может быть пустым'))
    }
    if(!password || password.length < 3){
        return Promise.reject(new Error('Пароль должен содержать не менее 3 символов'))
    }
    const cleanUser = username.trim()
    const lowerUser = cleanUser.toLowerCase()
    const passwordHash = crypto.createHash('sha256').update(password).digest('hex')

    // Find any existing account matching this username case-insensitively
    const accounts = ConfigManager.getAuthAccounts() || {}
    let existingAccount = null
    for(const key of Object.keys(accounts)){
        const acc = accounts[key]
        if(acc && acc.displayName && acc.displayName.toLowerCase() === lowerUser){
            existingAccount = acc
            break
        }
    }

    // Check stored password in account or in persistent userPasswords database
    const storedHash = (existingAccount && existingAccount.passwordHash) || (ConfigManager.getUserPasswordHash ? ConfigManager.getUserPasswordHash(lowerUser) : null)

    if(storedHash && storedHash !== passwordHash){
        return Promise.reject(new Error(`Неверный пароль для никнейма «${cleanUser}»!`))
    }

    if(existingAccount){
        existingAccount.type = 'community'
        existingAccount.passwordHash = passwordHash
        if(existingAccount.microsoft) delete existingAccount.microsoft
        if(existingAccount.expiresAt) delete existingAccount.expiresAt
        if(existingAccount.accessToken && existingAccount.accessToken !== '0') existingAccount.accessToken = '0'
        if(ConfigManager.setUserPasswordHash) ConfigManager.setUserPasswordHash(lowerUser, passwordHash)
        ConfigManager.setSelectedAccount(existingAccount.uuid)
        ConfigManager.save()
        return existingAccount
    }

    const uuid = generateOfflineUUID(cleanUser)
    const ret = ConfigManager.addCommunityAuthAccount(uuid, cleanUser, passwordHash)
    if(ConfigManager.setUserPasswordHash) ConfigManager.setUserPasswordHash(lowerUser, passwordHash)
    ConfigManager.save()
    return ret
}

